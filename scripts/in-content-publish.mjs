import fs from 'node:fs';
import assert from 'node:assert/strict';
import {testLoader} from './pack-test-utils.mjs';
const load=testLoader();
const {publishedInQuestions,inQuestions}=load('data/in-questions.ts');
const {inCards}=load('data/in-cards.ts');
const questions=publishedInQuestions(),free=questions.filter(q=>q.is_free);
assert.ok(free.every(q=>q.state==='IN'&&q.status==='published'));
fs.writeFileSync('data/in-free-questions.ts','import type { Question } from "@/lib/types";\n// Generated by scripts/in-content-publish.mjs: public free items only.\nexport const inFreeQuestions: Question[] = '+JSON.stringify(free,null,2)+';\n');
fs.writeFileSync('data/in-public-cards.ts','// Generated by scripts/in-content-publish.mjs: verified published cards only.\nexport const inPublicCards = '+JSON.stringify(inCards,null,2)+';\n');
const counts={candidate:inQuestions.length,draft:inQuestions.length-questions.length,published:questions.length,free:free.length,pro:questions.length-free.length};
let summary=fs.readFileSync('data/in-bank-summary.ts','utf8');
summary=summary.replace(/export const inBankCounts = [^;]+;/,'export const inBankCounts = '+JSON.stringify(counts)+';');
fs.writeFileSync('data/in-bank-summary.ts',summary);
console.log(JSON.stringify({questions:counts,independentCards:inCards.length}));
