import assert from 'node:assert/strict';
import fs from 'node:fs';
import { testLoader } from './pack-test-utils.mjs';

process.env.VERCEL_ENV = 'production';
process.env.STATE_PREVIEW = '1';
const load = testLoader();
const { productionStateBlocked, prepPageEnabled } = load('lib/state-release.ts');
assert.equal(productionStateBlocked('LA'), false, 'The pending LA opening candidate must enable LA learning');
assert.equal(productionStateBlocked('PA'), false, 'Retain published PA');
assert.equal(prepPageEnabled('louisiana'), true);
const { prepPacks } = load('lib/prep-pack.ts');
const { stateByCode } = load('lib/states.ts');
assert.equal(prepPacks.LA.available, true);
assert.equal(prepPacks.PA.available, true);
assert.equal(stateByCode('LA').homePath, '/louisiana/');
assert.equal(stateByCode('LA').status, 'available');
const { switchStateHref } = load('lib/ca-site.ts');
assert.equal(switchStateHref('/pennsylvania/practice/?mode=full', 'LA'), '/louisiana/practice/');
assert.equal(switchStateHref('/louisiana/practice/', 'PA'), '/pennsylvania/practice/');
const { laArticles, laReferenceArticles } = load('data/la-articles.ts');
assert.equal(prepPacks.LA.questions().length, 203);
assert.equal(prepPacks.LA.questions().filter(question => question.is_free).length, 29);
assert.equal(prepPacks.LA.cards.length, 54);
assert.equal(laArticles.length, 10);
assert.doesNotMatch(JSON.stringify([laArticles, laReferenceArticles]), /\/preview\/louisiana/);
const sitemap = load('app/sitemap.ts').default().map(entry => new URL(entry.url).pathname);
for (const path of [prepPacks.LA.paths.home, prepPacks.LA.paths.practice, prepPacks.LA.paths.pricing, ...laArticles.map(article => article.path), ...Object.values(laReferenceArticles).map(article => article.path)]) assert.ok(sitemap.includes(path), path);
assert.ok(sitemap.includes('/pennsylvania/practice/'));
assert.ok(!sitemap.some(path => path.startsWith('/preview/')));
for (const route of ['', 'practice/', 'questions/', 'study-guide/', 'study-cards/', 'wrong-answers/', 'daily-study/', 'resources/', 'exam-guide/', 'passing-score/', 'laws/', 'become-a-notary/', 'pricing/']) assert.ok(fs.existsSync('app/louisiana/' + route + 'page.tsx'));
console.log('LA public routes, bank/card counts, state switching and sitemap passed');
